export const SEVERITY = Object.freeze({
  ERROR: 'error',
  WARNING: 'warning'
});

export class GqlCageError extends Error {
  constructor(code, message, options = {}) {
    super(message);
    this.name = 'GqlCageError';
    this.code = code;
    if (typeof options.line === 'number') this.line = options.line;
    if (typeof options.column === 'number') this.column = options.column;
    if (typeof options.index === 'number') this.index = options.index;
    if (options.details !== undefined) this.details = options.details;
  }
}

export function gqlcageError(code, message, options = {}) {
  return new GqlCageError(code, message, options);
}

export function isGqlCageError(value) {
  return value instanceof GqlCageError || Boolean(value && value.name === 'GqlCageError' && typeof value.code === 'string');
}
